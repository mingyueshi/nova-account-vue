export const NOVA_ICON_NAMES = Object.freeze(Object.keys(components))
export function resolveNovaIcon(name: string): Component | undefined {
  const key = name.replace(/^custom:/, '')
  return Object.hasOwn(components, key) ? components[key] : undefined
}
